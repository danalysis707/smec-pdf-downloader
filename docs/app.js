// ── State ──────────────────────────────────────────────────────────────────
let allQuestions = [];
let themeMap = {};
let youtubeData = {};   // {subject: {theme: [{title, url, channel}]}}
let selectedSubject = '';
let selectedThemes = new Set();
let selectedYears = new Set();
let sessionQuestions = [];
let currentIndex = 0;
let sessionCorrect = 0;

const YEAR_LABELS = {
  r02: '令和2年度', r03: '令和3年度', r04: '令和4年度',
  r05: '令和5年度', r06: '令和6年度', r07: '令和7年度',
};

// ── Initialization ──────────────────────────────────────────────────────────
async function init() {
  const [qRes, tRes] = await Promise.all([
    fetch('data/quiz_data.json'),
    fetch('data/theme_map.json'),
  ]);
  allQuestions = (await qRes.json()).questions;
  themeMap = await tRes.json();

  // youtube_data.json is optional — generated by fetch_youtube.py
  try {
    const yRes = await fetch('data/youtube_data.json');
    if (yRes.ok) youtubeData = await yRes.json();
  } catch (_) { /* youtube data not available yet */ }

  renderSubjectList();
  renderYearList();
  updateStartButton();
}

// ── Filter UI ───────────────────────────────────────────────────────────────
function renderSubjectList() {
  const subjects = [...new Set(allQuestions.map(q => q.subject))];
  const container = document.getElementById('subject-list');
  container.innerHTML = subjects.map(s => `
    <button class="subject-btn" data-subject="${s}" onclick="selectSubject('${s}')">
      ${s}
    </button>
  `).join('');
}

function selectSubject(subject) {
  selectedSubject = subject;
  selectedThemes.clear();
  document.querySelectorAll('.subject-btn').forEach(btn => {
    btn.classList.toggle('selected', btn.dataset.subject === subject);
  });
  renderThemeList(subject);
  updateStartButton();
}

function renderThemeList(subject) {
  const themes = themeMap[subject] ? Object.keys(themeMap[subject]) : [];
  const container = document.getElementById('theme-list');
  container.innerHTML = themes.map(t => `
    <span class="chip" data-theme="${t}" onclick="toggleTheme('${t}', this)">${t}</span>
  `).join('');
  document.getElementById('theme-section').style.display = themes.length ? '' : 'none';
}

function toggleTheme(theme, el) {
  if (selectedThemes.has(theme)) {
    selectedThemes.delete(theme);
    el.classList.remove('selected');
  } else {
    selectedThemes.add(theme);
    el.classList.add('selected');
  }
  updateStartButton();
}

function renderYearList() {
  const years = [...new Set(allQuestions.map(q => q.year))].sort();
  const container = document.getElementById('year-list');
  container.innerHTML = years.map(y => `
    <span class="chip" data-year="${y}" onclick="toggleYear('${y}', this)">
      ${YEAR_LABELS[y] || y}
    </span>
  `).join('');
}

function toggleYear(year, el) {
  if (selectedYears.has(year)) {
    selectedYears.delete(year);
    el.classList.remove('selected');
  } else {
    selectedYears.add(year);
    el.classList.add('selected');
  }
  updateStartButton();
}

function getFilteredQuestions() {
  return allQuestions.filter(q => {
    if (!selectedSubject || q.subject !== selectedSubject) return false;
    if (selectedThemes.size > 0 && !selectedThemes.has(q.theme)) return false;
    if (selectedYears.size > 0 && !selectedYears.has(q.year)) return false;
    return true;
  });
}

function updateStartButton() {
  const btn = document.getElementById('start-btn');
  const count = getFilteredQuestions().length;
  if (!selectedSubject) {
    btn.textContent = '科目を選択してください';
    btn.disabled = true;
  } else if (count === 0) {
    btn.textContent = '該当する問題がありません';
    btn.disabled = true;
  } else {
    btn.textContent = `▶ 学習開始（${count}問）`;
    btn.disabled = false;
  }
}

// ── Question display ─────────────────────────────────────────────────────────
function showScreen(id) {
  document.querySelectorAll('.screen').forEach(s => s.classList.remove('active'));
  document.getElementById(id).classList.add('active');
}

function startQuiz() {
  sessionQuestions = getFilteredQuestions().sort(() => Math.random() - 0.5);
  currentIndex = 0;
  sessionCorrect = 0;
  showScreen('screen-question');
  renderQuestion();
}

function renderQuestion() {
  const q = sessionQuestions[currentIndex];

  // Source bar
  document.getElementById('src-year').textContent = q.year_label;
  document.getElementById('src-subject').textContent = q.subject;
  document.getElementById('src-qnum').textContent = `第${q.question_number}問`;

  // Meta
  document.getElementById('theme-badge').textContent = q.theme;
  document.getElementById('progress-text').textContent =
    `${currentIndex + 1} / ${sessionQuestions.length}問`;

  // Images
  const imgContainer = document.getElementById('question-images');
  imgContainer.innerHTML = q.pages.map(src =>
    `<img src="${src}" alt="第${q.question_number}問" loading="lazy">`
  ).join('');

  // Answer buttons (ア〜オ)
  const btns = document.getElementById('answer-buttons');
  btns.innerHTML = ['ア', 'イ', 'ウ', 'エ', 'オ'].map(ch => `
    <button class="ans-btn" onclick="submitAnswer('${ch}')">${ch}</button>
  `).join('');

  // Search link (before answer)
  const searchQ = document.getElementById('search-link-q');
  searchQ.href = `https://www.google.com/search?q=${encodeURIComponent(q.search_query)}`;
  searchQ.removeAttribute('aria-disabled');

  // Load memo
  document.getElementById('memo-text').value =
    localStorage.getItem(`memo_${q.id}`) || '';

  // Reset result section
  document.getElementById('answer-area').classList.remove('hidden');
  document.getElementById('result-section').classList.add('hidden');
}

// ── Wiring ───────────────────────────────────────────────────────────────────
document.getElementById('start-btn').addEventListener('click', startQuiz);
document.getElementById('back-btn').addEventListener('click', () => showScreen('screen-filter'));
document.getElementById('retry-btn').addEventListener('click', () => {
  currentIndex = 0;
  sessionCorrect = 0;
  sessionQuestions.sort(() => Math.random() - 0.5);
  showScreen('screen-question');
  renderQuestion();
});

init();
