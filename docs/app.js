// ── State ──────────────────────────────────────────────────────────────────
let allQuestions = [];
let themeMap = {};
let youtubeData = {};   // {subject: {theme: [{title, url, channel}]}}
let selectedSubject = '';
let selectedThemes = new Set();
let selectedYears = new Set();
let sessionQuestions = [];
let currentIndex = 0;
let sessionCorrect = 0;

const YEAR_LABELS = {
  r02: '令和2年度', r03: '令和3年度', r04: '令和4年度',
  r05: '令和5年度', r06: '令和6年度', r07: '令和7年度',
};

// ── Helpers ─────────────────────────────────────────────────────────────────
function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// ── Initialization ──────────────────────────────────────────────────────────
async function init() {
  try {
    const [qRes, tRes] = await Promise.all([
      fetch('data/quiz_data.json'),
      fetch('data/theme_map.json'),
    ]);
    if (!qRes.ok || !tRes.ok) throw new Error('データの読み込みに失敗しました');
    allQuestions = (await qRes.json()).questions;
    themeMap = await tRes.json();
  } catch (err) {
    document.getElementById('subject-list').textContent = `エラー: ${err.message}`;
    return;
  }

  // youtube_data.json is optional — generated by fetch_youtube.py
  try {
    const yRes = await fetch('data/youtube_data.json');
    if (yRes.ok) youtubeData = await yRes.json();
  } catch (_) { /* youtube data not available yet */ }

  renderSubjectList();
  renderYearList();
  updateStartButton();
}

// ── Filter UI ───────────────────────────────────────────────────────────────
function renderSubjectList() {
  const subjects = [...new Set(allQuestions.map(q => q.subject))];
  const container = document.getElementById('subject-list');
  container.innerHTML = '';
  subjects.forEach(s => {
    const btn = document.createElement('button');
    btn.className = 'subject-btn';
    btn.dataset.subject = s;
    btn.textContent = s;
    btn.addEventListener('click', () => selectSubject(s));
    container.appendChild(btn);
  });
}

function selectSubject(subject) {
  selectedSubject = subject;
  selectedThemes.clear();
  document.querySelectorAll('.subject-btn').forEach(btn => {
    btn.classList.toggle('selected', btn.dataset.subject === subject);
  });
  renderThemeList(subject);
  updateStartButton();
}

function renderThemeList(subject) {
  const themes = themeMap[subject] ? Object.keys(themeMap[subject]) : [];
  const container = document.getElementById('theme-list');
  container.innerHTML = '';
  themes.forEach(t => {
    const chip = document.createElement('span');
    chip.className = 'chip';
    chip.dataset.theme = t;
    chip.textContent = t;
    chip.addEventListener('click', () => toggleTheme(t, chip));
    container.appendChild(chip);
  });
  document.getElementById('theme-section').style.display = themes.length ? '' : 'none';
}

function toggleTheme(theme, el) {
  if (selectedThemes.has(theme)) {
    selectedThemes.delete(theme);
    el.classList.remove('selected');
  } else {
    selectedThemes.add(theme);
    el.classList.add('selected');
  }
  updateStartButton();
}

function renderYearList() {
  const years = [...new Set(allQuestions.map(q => q.year))].sort();
  const container = document.getElementById('year-list');
  container.innerHTML = '';
  years.forEach(y => {
    const chip = document.createElement('span');
    chip.className = 'chip';
    chip.dataset.year = y;
    chip.textContent = YEAR_LABELS[y] || y;
    chip.addEventListener('click', () => toggleYear(y, chip));
    container.appendChild(chip);
  });
}

function toggleYear(year, el) {
  if (selectedYears.has(year)) {
    selectedYears.delete(year);
    el.classList.remove('selected');
  } else {
    selectedYears.add(year);
    el.classList.add('selected');
  }
  updateStartButton();
}

function getFilteredQuestions() {
  return allQuestions.filter(q => {
    if (!selectedSubject || q.subject !== selectedSubject) return false;
    if (selectedThemes.size > 0 && !selectedThemes.has(q.theme)) return false;
    if (selectedYears.size > 0 && !selectedYears.has(q.year)) return false;
    return true;
  });
}

function updateStartButton() {
  const btn = document.getElementById('start-btn');
  const count = getFilteredQuestions().length;
  if (!selectedSubject) {
    btn.textContent = '科目を選択してください';
    btn.disabled = true;
  } else if (count === 0) {
    btn.textContent = '該当する問題がありません';
    btn.disabled = true;
  } else {
    btn.textContent = `▶ 学習開始（${count}問）`;
    btn.disabled = false;
  }
}

// ── Question display ─────────────────────────────────────────────────────────
function showScreen(id) {
  document.querySelectorAll('.screen').forEach(s => s.classList.remove('active'));
  document.getElementById(id).classList.add('active');
}

function startQuiz() {
  sessionQuestions = shuffle(getFilteredQuestions());
  currentIndex = 0;
  sessionCorrect = 0;
  showScreen('screen-question');
  renderQuestion();
}

function renderQuestion() {
  const q = sessionQuestions[currentIndex];

  // Source bar
  document.getElementById('src-year').textContent = q.year_label;
  document.getElementById('src-subject').textContent = q.subject;
  document.getElementById('src-qnum').textContent = `第${q.question_number}問`;

  // Meta
  document.getElementById('theme-badge').textContent = q.theme;
  document.getElementById('progress-text').textContent =
    `${currentIndex + 1} / ${sessionQuestions.length}問`;

  // Images
  const imgContainer = document.getElementById('question-images');
  const pages = q.pages || [];
  imgContainer.innerHTML = '';
  pages.forEach(src => {
    const img = document.createElement('img');
    img.src = src;
    img.alt = `第${q.question_number}問`;
    img.loading = 'lazy';
    imgContainer.appendChild(img);
  });
  if (!pages.length) {
    imgContainer.textContent = '（画像なし）';
  }

  // Answer prompt label
  document.getElementById('answer-prompt').textContent =
    `第${q.question_number}問の解答を選んでください`;

  // Prev button — visible only when not on first question
  document.getElementById('prev-btn').classList.toggle('hidden', currentIndex === 0);

  // Answer buttons (ア〜オ) — use createElement to avoid global onclick
  const btns = document.getElementById('answer-buttons');
  btns.innerHTML = '';
  ['ア', 'イ', 'ウ', 'エ', 'オ'].forEach(ch => {
    const btn = document.createElement('button');
    btn.className = 'ans-btn';
    btn.textContent = ch;
    btn.addEventListener('click', () => submitAnswer(ch));
    btns.appendChild(btn);
  });

  // Search link (before answer)
  const searchQ = document.getElementById('search-link-q');
  searchQ.href = `https://www.google.com/search?q=${encodeURIComponent(q.search_query)}`;
  searchQ.removeAttribute('aria-disabled');

  // Load memo
  document.getElementById('memo-text').value =
    localStorage.getItem(`memo_${q.id}`) || '';

  // Reset result section
  document.getElementById('answer-area').classList.remove('hidden');
  document.getElementById('result-section').classList.add('hidden');
}

// ── Answer & Result ──────────────────────────────────────────────────────────
function submitAnswer(choice) {
  document.querySelectorAll('.ans-btn').forEach(btn => {
    btn.disabled = true;
    if (btn.textContent === choice) btn.classList.add('selected');
  });

  const q = sessionQuestions[currentIndex];
  const isCorrect = !!q.correct_answer && choice === q.correct_answer;
  if (isCorrect) sessionCorrect++;

  localStorage.setItem(`result_${q.id}`, JSON.stringify({
    answer: choice,
    correct: q.correct_answer,
    isCorrect,
    timestamp: Date.now(),
  }));

  showResult(choice, q);
}

function showResult(yourAnswer, q) {
  const isCorrect = yourAnswer === q.correct_answer;

  const badge = document.getElementById('result-badge');
  if (!q.correct_answer) {
    badge.textContent = '📋 正解を確認（解答PDFから取得できませんでした）';
    badge.className = 'result-badge unknown';
  } else {
    badge.textContent = isCorrect ? '⭕ 正解！' : '❌ 不正解';
    badge.className = `result-badge ${isCorrect ? 'correct' : 'wrong'}`;
  }

  document.getElementById('correct-val').textContent = q.correct_answer || '（未取得）';
  document.getElementById('your-val').textContent = yourAnswer;

  // Prev button in result section
  document.getElementById('result-prev-btn').classList.toggle('hidden', currentIndex === 0);

  // やり直しボタン — 不正解・正解未取得のときのみ表示
  document.getElementById('retry-q-btn').classList.toggle('hidden', isCorrect);

  const searchR = document.getElementById('search-link-r');
  searchR.href = `https://www.google.com/search?q=${encodeURIComponent(q.search_query)}`;
  searchR.removeAttribute('aria-disabled');

  // YouTube links (optional — requires youtube_data.json generated by fetch_youtube.py)
  const ytContainer = document.getElementById('youtube-links');
  const videos = (youtubeData[q.subject] || {})[q.theme] || [];
  if (videos.length) {
    ytContainer.innerHTML = '';
    const label = document.createElement('div');
    label.className = 'yt-label';
    label.textContent = '▶ 関連動画';
    ytContainer.appendChild(label);
    videos.forEach(v => {
      const a = document.createElement('a');
      a.className = 'yt-link';
      a.href = v.url;
      a.target = '_blank';
      a.rel = 'noopener';
      a.textContent = `${v.title}（${v.channel}）`;
      ytContainer.appendChild(a);
    });
    ytContainer.classList.remove('hidden');
  } else {
    ytContainer.classList.add('hidden');
  }

  document.getElementById('prev-btn').classList.add('hidden');
  document.getElementById('answer-area').classList.add('hidden');
  document.getElementById('result-section').classList.remove('hidden');
}

function saveMemo() {
  const q = sessionQuestions[currentIndex];
  if (!q) return;
  const text = document.getElementById('memo-text').value;
  if (text.trim()) {
    localStorage.setItem(`memo_${q.id}`, text);
  } else {
    localStorage.removeItem(`memo_${q.id}`);
  }
}

function prevQuestion() {
  if (currentIndex > 0) {
    currentIndex--;
    renderQuestion();
  }
}

function retryQuestion() {
  renderQuestion();
}

function nextQuestion() {
  saveMemo();
  currentIndex++;
  if (currentIndex >= sessionQuestions.length) {
    showComplete();
  } else {
    renderQuestion();
  }
}

function showComplete() {
  document.getElementById('final-score').textContent =
    `${sessionCorrect} / ${sessionQuestions.length} 問正解`;
  showScreen('screen-complete');
}

// ── Boot ─────────────────────────────────────────────────────────────────────
document.addEventListener('DOMContentLoaded', () => {
  document.getElementById('start-btn').addEventListener('click', startQuiz);
  document.getElementById('menu-btn').addEventListener('click', () => showScreen('screen-filter'));
  document.getElementById('prev-btn').addEventListener('click', prevQuestion);
  document.getElementById('back-btn').addEventListener('click', () => showScreen('screen-filter'));
  document.getElementById('retry-btn').addEventListener('click', () => {
    currentIndex = 0;
    sessionCorrect = 0;
    shuffle(sessionQuestions);
    showScreen('screen-question');
    renderQuestion();
  });
  document.getElementById('next-btn').addEventListener('click', nextQuestion);
  document.getElementById('result-prev-btn').addEventListener('click', prevQuestion);
  document.getElementById('retry-q-btn').addEventListener('click', retryQuestion);
  document.getElementById('memo-text').addEventListener('input', saveMemo);
  init();
});
